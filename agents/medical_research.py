
import json
import logging
from typing import Any

from langchain_core.messages import HumanMessage, SystemMessage
from langchain_ollama import ChatOllama
from pydantic import BaseModel, ConfigDict, Field

from config.settings import settings
from tools.medical_research_tools import search_medical_references


logger = logging.getLogger(__name__)


# ---------------------------------------------------------
# 1. MEDICAL RESEARCH PROMPT
# ---------------------------------------------------------

MEDICAL_RESEARCH_PROMPT = """
You are a Medical Research Summarization Agent.

Your task is to analyze the PubMed article abstracts supplied
in the user message.

You MUST produce:
1. A meaningful research summary.
2. At least one key finding for every article with a usable abstract.
3. Relevant limitations of the available evidence.

STRICT RULES:

- Use only the supplied article titles and abstracts.
- Do not invent facts, statistics or findings.
- Do not invent article references.
- Do not make personal medical recommendations.
- Do not diagnose patients.
- Do not prescribe medication or treatment.
- Do not claim that a study proves a medical condition.
- Distinguish findings from uncertainty.
- If an abstract does not provide enough information,
  explain that limitation.
- Keep findings specific to the supplied articles.

For key findings:
- Extract concrete findings from the abstracts.
- Do not simply repeat the article titles.
- Keep each finding concise.
- Include findings from different articles where possible.

For limitations:
- Mention limitations that can actually be inferred
  from the supplied information.
- Do not invent study limitations.
- If the abstract does not describe limitations,
  say that the abstract does not provide enough detail
  to assess them.

Your output must be informative and evidence-based.
"""


# ---------------------------------------------------------
# 2. STRUCTURED SUMMARY MODEL
# ---------------------------------------------------------

class ResearchSummary(BaseModel):
    """Structured summary generated by Ollama."""

    model_config = ConfigDict(extra="forbid")

    research_summary: str = Field(
        description="A detailed summary of the supplied research."
    )

    key_findings: list[str] = Field(
        description="Concrete findings extracted from the abstracts."
    )

    limitations: list[str] = Field(
        description="Evidence limitations supported by the supplied material."
    )


# ---------------------------------------------------------
# 3. MEDICAL RESEARCH AGENT
# ---------------------------------------------------------

def run_medical_research(
    query: str,
    max_results: int = 5,
) -> dict[str, Any]:
    """
    Search PubMed and summarize retrieved medical research.

    PubMed supplies original article information.
    Ollama summarizes the article abstracts.

    References are never generated by the LLM.
    """

    if not isinstance(query, str) or not query.strip():
        raise ValueError("Medical research query cannot be empty.")

    if not isinstance(max_results, int) or isinstance(max_results, bool):
        raise ValueError("max_results must be an integer.")

    if not 1 <= max_results <= 10:
        raise ValueError("max_results must be between 1 and 10.")

    search_query = query.strip()

    try:
        # -------------------------------------------------
        # STEP 1: SEARCH PUBMED
        # -------------------------------------------------

        raw_result = search_medical_references.invoke({
            "query": search_query,
            "max_results": max_results,
        })

        pubmed_data = (
            json.loads(raw_result)
            if isinstance(raw_result, str)
            else raw_result
        )

        if not isinstance(pubmed_data, dict):
            raise ValueError("Invalid PubMed response.")

        if not pubmed_data.get("success"):
            raise RuntimeError(
                pubmed_data.get("error", "PubMed search failed.")
            )

        articles = pubmed_data.get("articles", [])

        if not isinstance(articles, list):
            raise ValueError("Invalid article collection.")

        # -------------------------------------------------
        # STEP 2: PRESERVE ORIGINAL REFERENCES
        # -------------------------------------------------

        references = []

        for article in articles:

            if not isinstance(article, dict):
                continue

            references.append({
                "pubmed_id": article.get("pubmed_id", ""),
                "title": article.get("title", ""),
                "authors": article.get("authors", []),
                "journal": article.get("journal", ""),
                "publication_date": article.get("publication_date", ""),
                "pubmed_url": article.get("pubmed_url", ""),
            })

        actual_count = len(references)

        if actual_count == 0:
            return {
                "search_query": search_query,
                "total_found": pubmed_data.get("total_found", 0),
                "articles_found": 0,
                "research_summary": "No matching research articles were found.",
                "key_findings": [],
                "limitations": [
                    "No research articles were available for analysis."
                ],
                "references": [],
            }

        # -------------------------------------------------
        # STEP 3: PREPARE ABSTRACTS
        # -------------------------------------------------

        articles_with_abstracts = []

        for article in articles:

            if not isinstance(article, dict):
                continue

            abstract = article.get("abstract", "").strip()

            if abstract:
                articles_with_abstracts.append({
                    "title": article.get("title", ""),
                    "abstract": abstract,
                })

        if not articles_with_abstracts:
            return {
                "search_query": search_query,
                "total_found": pubmed_data.get("total_found", actual_count),
                "articles_found": actual_count,
                "research_summary": (
                    "Articles were retrieved, but their abstracts "
                    "were not available for summarization."
                ),
                "key_findings": [],
                "limitations": [
                    "The retrieved records did not contain usable abstracts."
                ],
                "references": references,
            }

        # -------------------------------------------------
        # STEP 4: PREPARE RESEARCH CONTENT
        # -------------------------------------------------

        research_material = []

        for index, article in enumerate(
            articles_with_abstracts,
            start=1,
        ):
            research_material.append(
                f"""
                ARTICLE {index}

                TITLE:
                {article["title"]}

                ABSTRACT:
                {article["abstract"]}
                """
            )

        research_text = "\n".join(research_material)

        # -------------------------------------------------
        # STEP 5: SUMMARIZE USING OLLAMA
        # -------------------------------------------------

        model = ChatOllama(
            model=settings.ollama_model,
            base_url=settings.ollama_base_url,
            temperature=0,
        )

        structured_model = model.with_structured_output(
            ResearchSummary
        )

        messages = [
            SystemMessage(content=MEDICAL_RESEARCH_PROMPT),
            HumanMessage(
                content=f"""
                RESEARCH QUERY:
                {search_query}

                NUMBER OF ARTICLES WITH ABSTRACTS:
                {len(articles_with_abstracts)}

                RESEARCH ARTICLES:
                {research_text}

                Produce a meaningful summary.

                Extract at least one concrete finding from each
                usable abstract. Do not return empty findings when
                the abstracts contain relevant information.
                """
            ),
        ]

        summary = structured_model.invoke(messages)

        if not isinstance(summary, ResearchSummary):
            summary = ResearchSummary.model_validate(summary)

        # -------------------------------------------------
        # STEP 6: VALIDATE SUMMARY
        # -------------------------------------------------

        if not summary.research_summary.strip():
            raise ValueError("Research summary is empty.")

        if not summary.key_findings:
            raise ValueError(
                "Ollama did not extract any key findings."
            )

        if len(summary.key_findings) < len(articles_with_abstracts):
            logger.warning(
                "Fewer findings than abstracts were returned."
            )

        # -------------------------------------------------
        # STEP 7: RETURN FINAL RESULT
        # -------------------------------------------------

        return {
            "search_query": search_query,
            "total_found": pubmed_data.get("total_found", actual_count),
            "articles_found": actual_count,
            "abstracts_analyzed": len(articles_with_abstracts),
            "research_summary": summary.research_summary,
            "key_findings": summary.key_findings,
            "limitations": summary.limitations,
            "references": references,
        }

    except Exception as exc:
        logger.exception("Medical research agent failed.")

        raise RuntimeError(
            "Medical research failed. Check PubMed connectivity "
            "and Ollama summarization."
        ) from exc
